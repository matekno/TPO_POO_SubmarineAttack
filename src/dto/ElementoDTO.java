package dto;

public class ElementoDTO {
    private final double x;
    private final double y;
    private final double ancho;
    private final double alto;

    public ElementoDTO(double x, double y, double ancho, double alto) {
        this.x = x;
        this.y = y;
        this.ancho = ancho;
        this.alto = alto;
    }

    public double getX() {
        return x;
    }

    public double getY() {
        return y;
    }

    public double getAncho() {
        return ancho;
    }

    public double getAlto() {
        return alto;
    }
}